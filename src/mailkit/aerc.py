"""aerc, one of the possible readers: an accounts.conf generated per run.

Two accounts per mailkit account:
- `<handle>`: live over IMAP, nothing local involved. Credentials through
  `mailkit secret get`, so a locked keyring means aerc cannot log in.
- `archive-<handle>`: the mirror's notmuch index. Queries only — the mirror is
  read-only (Sync Pull), so there is no delete or move to offer.

The user's own aerc.conf and binds.conf are used as they are; only the
accounts file is mailkit's, passed with -A.
"""

from __future__ import annotations

import shlex
import subprocess
from urllib.parse import quote

from .config import Account, Instance, Server
from .util import MailkitError, child_env, runtime_dir, self_cmd, write_private

QUERY_MAP = """Inbox=tag:inbox and not tag:deleted
Unread=tag:unread and not tag:spam and not tag:deleted
Drafts=tag:draft
Review=tag:review
Sent=tag:sent
All=not tag:spam and not tag:deleted
Spam=tag:spam
Trash=tag:deleted
"""


def _url(scheme: str, a: Account, s: Server) -> str:
    return f"{scheme}://{quote(a.login, safe='')}@{s.host}:{s.port}"


def _imap(a: Account) -> str:
    return _url({"tls": "imaps", "starttls": "imap", "none": "imap+insecure"}[a.imap.tls], a, a.imap)


def _smtp(a: Account) -> str:
    return _url({"tls": "smtps", "starttls": "smtp", "none": "smtp+insecure"}[a.smtp.tls], a, a.smtp)


def accounts_conf(inst: Instance, query_map: str) -> str:
    out = [f"# Generated by mailkit from {inst.config_path} — edits are overwritten.\n"]
    for a in inst.accounts.values():
        cred = shlex.join([*self_cmd(), "secret", "get", a.handle, "password"])
        common = f"""from = {a.from_header}
outgoing = {_smtp(a)}
outgoing-cred-cmd = {cred}
"""
        live = f"""[{a.handle}]
source = {_imap(a)}
source-cred-cmd = {cred}
{common}default = {a.folders.inbox}
"""
        if a.folders.sent and a.sent_copy:
            live += f"copy-to = {a.folders.sent}\n"
        if a.folders.drafts:
            live += f"postpone = {a.folders.drafts}\n"
        out.append(live + "\n")
        out.append(f"""[archive-{a.handle}]
source = notmuch://{a.profile}
enable-maildir = false
query-map = {query_map}
default = Inbox
{common}
""")
    return "".join(out)


def run(inst: Instance, names: list[str]) -> int:
    d = runtime_dir(inst.name)
    qm = d / "aerc-query-map"
    write_private(qm, QUERY_MAP)
    conf = d / "aerc-accounts.conf"
    # 0600: aerc refuses a world-readable accounts.conf.
    write_private(conf, accounts_conf(inst, str(qm)))
    try:
        return subprocess.run(["aerc", "-A", str(conf), "-a", ",".join(names)],
                              env=child_env(inst.config_path)).returncode
    except FileNotFoundError:
        raise MailkitError("aerc not found on PATH (it is optional: every other command works without it)") from None
