"""notmuch: one profile and one index per account, the index INSIDE the store.

The Xapian index holds the full text of every message: it is exactly as
sensitive as the Maildir it indexes, so it lives behind the same seal. A
shared index would undo the per-account isolation.

Profiles live where libnotmuch looks for them, $XDG_CONFIG_HOME/notmuch/<profile>/,
because aerc opens the database by profile name only (`notmuch://<profile>`).
They hold paths, never secrets, and are rewritten from the TOML on every run.
"""

from __future__ import annotations

import json
import os
import subprocess
import time
from email.utils import parseaddr
from pathlib import Path

from .config import Account
from .util import MailkitError

# Everything mbsync leaves lying around that is not a message.
SYNC_STATE = ".mbsyncstate;.mbsyncstate.journal;.mbsyncstate.new;.mbsyncstate.lock;.uidvalidity"


def local_folder(imap_name: str) -> str:
    """The directory mbsync gives an IMAP folder under `SubFolders Verbatim`.
    Servers whose personal namespace is `INBOX.` (Courier, many cPanel
    Dovecots) have it stripped: `INBOX.Sent Items` → `Sent Items`."""
    if len(imap_name) > 6 and imap_name[:5].upper() == "INBOX" and imap_name[5] in "./":
        return imap_name[6:]
    return imap_name


def profile_dir(a: Account) -> Path:
    base = os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config")
    return Path(base) / "notmuch" / a.profile


def write_profile(a: Account) -> None:
    text = f"""# Generated by mailkit from {a.instance.config_path} — edits are overwritten.
[database]
path={a.mountpoint}/.notmuch
mail_root={a.mountpoint}

[user]
name={a.name}
primary_email={a.address}

[new]
tags=unread;inbox
ignore={SYNC_STATE}

[search]
exclude_tags=deleted;spam

[maildir]
synchronize_flags=true
"""
    d = profile_dir(a)
    d.mkdir(parents=True, exist_ok=True)
    cfg = d / "config"
    if not cfg.is_file() or cfg.read_text() != text:
        cfg.write_text(text)


def env(a: Account) -> dict[str, str]:
    e = dict(os.environ)
    # NOTMUCH_CONFIG beats NOTMUCH_PROFILE: one left over from a global setup
    # would silently point every account at the same index.
    e.pop("NOTMUCH_CONFIG", None)
    e["NOTMUCH_PROFILE"] = a.profile
    return e


def ensure(a: Account) -> None:
    """Before the first `notmuch new` there is no database, and notmuch says
    "Cannot open database at <store>/.notmuch/.notmuch" — true but useless.
    An empty index is the honest state of a store nothing was synced into."""
    write_profile(a)
    if not (a.mountpoint / ".notmuch" / "xapian").is_dir():
        subprocess.run(["notmuch", "new", "--quiet"], env=env(a), capture_output=True)


def run(a: Account, *args: str, input: str | None = None, check: bool = True) -> str:
    ensure(a)
    try:
        r = subprocess.run(["notmuch", *args], env=env(a), input=input,
                           capture_output=True, text=True)
    except FileNotFoundError:
        raise MailkitError("notmuch not found on PATH") from None
    if check and r.returncode != 0:
        raise MailkitError(f"{a.handle}: notmuch {args[0]} failed: {r.stderr.strip()}")
    return r.stdout


def _q(folder: str) -> str:
    return '"' + folder.replace('"', '\\"') + '"'


def tag_rules(a: Account) -> list[str]:
    """`notmuch tag --batch` lines applied after every `notmuch new`.

    Only the mirror's INBOX means inbox: Gmail also files an archived message
    under "[Gmail]/All" (localised), which must not bring it back."""
    f = a.folders
    inbox = f"mail/{local_folder(f.inbox)}"
    rules = [f"-inbox -- tag:inbox and not folder:{_q(inbox)}"]
    if f.sent:
        rules.append(f"+sent -unread -- folder:{_q('mail/' + local_folder(f.sent))} and not tag:sent")
    if f.spam:
        rules.append(f"+spam -- folder:{_q('mail/' + local_folder(f.spam))} and not tag:spam")
    if f.trash:
        rules.append(f"+deleted -- folder:{_q('mail/' + local_folder(f.trash))} and not tag:deleted")
    if f.drafts:
        # The server's drafts folder (aerc's :postpone) — not mailkit's outbox.
        rules.append(f"-unread -- folder:{_q('mail/' + local_folder(f.drafts))} and tag:unread")
    rules += [
        '+draft -unread -- path:"outbox/**" and not tag:draft',
        '+review -- path:"outbox/**" and not tag:review and not tag:approved',
        '+sent -unread -- path:"sent/**" and not tag:sent',
    ]
    return rules


def update(a: Account) -> None:
    """`notmuch new` + the tag rules: picks up files that appeared or went away
    (a sync, a delivery). Not enough after mailkit itself creates, rewrites or
    replaces a message's file — that is `refresh`."""
    run(a, "new", "--quiet")
    run(a, "tag", "--batch", input="\n".join(tag_rules(a)) + "\n")


def refresh(a: Account, msgid: str) -> None:
    """`update` + `notmuch reindex id:<msgid>`: THE way mailkit updates the index
    after creating, rewriting, replacing or removing a message's file.

    notmuch takes a message's headers from the first file it indexed under
    that Message-ID and keeps them: a file rewritten in place, or a second
    file with the same id (the compiled copy in sent/ of a dateless draft),
    changes nothing until reindexed. Without this a sent message stays dated
    1970 and an edited draft keeps its first subject."""
    update(a)
    run(a, "reindex", f"id:{msgid}")


# A draft has no Date until it is sent (notmuch dates it 0); send always
# writes a dated copy to sent/, so a message there dated 1970 was indexed from
# its draft and never refreshed. Only sent/: mail from the server can lack a
# Date for real, and a reindex would not change it. Epoch bounds: notmuch 0.40
# matches nothing at 0 with an open `date:..1971`.
DATELESS = 'date:@0..@31535999 and path:"sent/**"'


def dateless(a: Account) -> int:
    return int(run(a, "count", DATELESS).strip() or 0)


def recent(a: Account, query: str = "", limit: int = 40) -> list[tuple[str, str, str, str]]:
    """(msgid, date, from, subject) of the newest messages matching `query`
    (default: everything), drafts left out — what reply/forward pick from."""
    q = f"({query}) and not tag:draft" if query else "not tag:draft"
    ids = [i.removeprefix("id:") for i in run(a, "search", "--output=messages", "--sort=newest-first",
                                              f"--limit={limit}", q).split("\n") if i]
    if not ids:
        return []
    shown = run(a, "show", "--format=json", "--body=false", "--entire-thread=false",
                " or ".join('id:"' + i.replace('"', '""') + '"' for i in ids))
    msgs: dict[str, dict] = {}

    def walk(node):  # threads → [message, replies] pairs, nested
        if isinstance(node, dict):
            msgs[node.get("id", "")] = node
        elif isinstance(node, list):
            for n in node:
                walk(n)

    walk(json.loads(shown or "[]"))
    rows = []
    for i in ids:
        m = msgs.get(i, {})
        h = m.get("headers", {})
        name, addr = parseaddr(h.get("From", ""))
        date = time.strftime("%Y-%m-%d", time.localtime(m.get("timestamp", 0)))
        rows.append((i, date, name or addr, " ".join(h.get("Subject", "").split())))
    return rows
