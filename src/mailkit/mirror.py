"""mbsync: a read-only mirror of the server, one channel per account.

`Sync Pull` + `Create Near`: the server is the truth and the mirror never
writes back — reading, tagging and indexing locally cannot touch a message on
the server. `Expunge Near` (per account: `expunge`) drops what the server
deleted; with `expunge = false` the mirror keeps it, flagged.

The rc is generated into the runtime dir on every run and passed with -c: a
reflexive `mbsync -a` finds nothing, so it can never write plaintext into a
closed (mode 500) mount point.
"""

from __future__ import annotations

import os
import shlex
import subprocess

from . import index, seal
from .config import Account, Instance
from .util import MailkitError, child_env, runtime_dir, self_cmd, write_private

CA_BUNDLES = ("/etc/ssl/certs/ca-certificates.crt", "/etc/pki/tls/certs/ca-bundle.crt")


def _tls(a: Account) -> str:
    return {"tls": "IMAPS", "starttls": "STARTTLS", "none": "None"}[a.imap.tls]


def rc(inst: Instance) -> str:
    ca = next((p for p in CA_BUNDLES if os.path.isfile(p)), None)
    out = [f"# Generated by mailkit from {inst.config_path} — edits are overwritten.\n"]
    for a in inst.accounts.values():
        passcmd = shlex.join([*self_cmd(), "secret", "get", a.handle, "password"])
        out.append(f"""IMAPAccount {a.handle}
Host {a.imap.host}
Port {a.imap.port}
User {a.login}
PassCmd {_mbsync_quote(passcmd)}
TLSType {_tls(a)}
{f"CertificateFile {ca}" if ca else ""}

IMAPStore {a.handle}-remote
Account {a.handle}

MaildirStore {a.handle}-local
Path {a.mirror}/
Inbox {a.mirror}/{index.local_folder(a.folders.inbox)}
SubFolders Verbatim

Channel {a.handle}
Far :{a.handle}-remote:
Near :{a.handle}-local:
Patterns *
Create Near
Expunge {"Near" if a.expunge else "None"}
Remove None
Sync Pull
SyncState *

""")
    return "".join(out)


def _mbsync_quote(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def sync(a: Account) -> None:
    seal.require_open(a)
    path = runtime_dir(a.instance.name) / "mbsyncrc"
    write_private(path, rc(a.instance))
    argv = ["mbsync", "-c", str(path), a.handle]
    try:
        r = subprocess.run(argv, env=child_env(a.instance.config_path))
    except FileNotFoundError:
        raise MailkitError("mbsync (isync) not found on PATH") from None
    if r.returncode != 0:
        raise MailkitError(f"{a.handle}: mbsync failed (exit {r.returncode})")
    index.update(a)
